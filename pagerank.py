"""
pagerank.py — Phase 6: which judgments are authoritative? PageRank on citations.

The idea: a judgment cited by many judgments, especially by judgments that
are themselves much cited, is authoritative. PageRank measures exactly that.

The citation graph: one node per document of our corpus; an edge u → v when
document u cites document v (from data/citations.tsv, written by crawl.py).
Only edges with both ends in the corpus are used.

Power iteration. Start with every document at 1/N. Then repeat:

    PR_new(v) = (1 − d) / N                       a random jump to any document
              + d · Σ PR(u) / outdeg(u)           shares passed on by documents citing v
                    over u citing v
              + d · (dangling mass) / N           documents citing nothing spread
                                                  their share evenly
    d = 0.85 (damping). Stop when the total change is below TOLERANCE.

The ranks always add up to 1. An average document has PageRank 1/N, so
PR · N > 1 means "more authoritative than average".

Statutes get very high PageRank (almost every criminal judgment cites the
IPC), but that says "this Act exists", not "this is the key authority on
your question". So ranking.py gives the PageRank bonus to JUDGMENTS only.

Output:
    data/pagerank.tsv        doc_id <TAB> doc_type <TAB> pagerank   (used by ranking.py)
    analysis/pagerank.md     graph statistics and the top documents

Run:
    python pagerank.py
"""

import json
import sys
from collections import defaultdict
from pathlib import Path

BASE_DIR        = Path(__file__).resolve().parent
CORPUS_FILE     = BASE_DIR / "data" / "corpus_dedup.jsonl"
CITATIONS_FILE  = BASE_DIR / "data" / "citations.tsv"
PAGERANK_FILE   = BASE_DIR / "data" / "pagerank.tsv"
REPORT_FILE     = BASE_DIR / "analysis" / "pagerank.md"

DAMPING   = 0.85
TOLERANCE = 1e-10           # stop when Σ |PR_new − PR| is below this
MAX_ITERATIONS = 200

def load_graph() -> tuple[list[str], dict[str, set[str]], dict[str, dict]]:
    """Nodes (corpus doc_ids), edges {citing: {cited, …}}, and document info."""
    info = {}
    with CORPUS_FILE.open(encoding="utf-8") as f:
        for line in f:
            doc = json.loads(line)
            info[doc["doc_id"]] = {"title": doc["title"], "type": doc["doc_type"]}
    cites = defaultdict(set)                       # a set: citing the same case twice counts once
    with CITATIONS_FILE.open(encoding="utf-8") as f:
        for line in f:
            src, dst = line.split()
            if src in info and dst in info and src != dst:
                cites[src].add(dst)
    return list(info), cites, info

def pagerank(nodes: list[str], cites: dict[str, set[str]]) -> tuple[dict[str, float], int]:
    """Power iteration. Returns ({doc_id: PageRank}, number of iterations)."""
    N = len(nodes)
    pr = {v: 1 / N for v in nodes}
    for iteration in range(1, MAX_ITERATIONS + 1):
        new = {v: (1 - DAMPING) / N for v in nodes}
        dangling = 0.0
        for u in nodes:
            if cites.get(u):
                share = DAMPING * pr[u] / len(cites[u])
                for v in cites[u]:
                    new[v] += share                # u passes its rank to what it cites
            else:
                dangling += pr[u]                  # u cites nothing in the corpus
        for v in nodes:
            new[v] += DAMPING * dangling / N
        change = sum(abs(new[v] - pr[v]) for v in nodes)
        pr = new
        if change < TOLERANCE:
            return pr, iteration
    return pr, MAX_ITERATIONS

def write_report(pr, cites, info, iterations) -> None:
    N = len(pr)
    edges = sum(len(c) for c in cites.values())
    cited_by = defaultdict(int)
    for targets in cites.values():
        for v in targets:
            cited_by[v] += 1
    ranked = sorted(pr, key=pr.get, reverse=True)

    def table(doc_ids):
        rows = ["| # | PR × N | cited by | Document |", "|---|---|---|---|"]
        rows += [f"| {i} | {pr[d] * N:.1f} | {cited_by[d]} | {info[d]['title'][:90]} |"
                 for i, d in enumerate(doc_ids, 1)]
        return rows

    lines = [
        "# PageRank on the citation graph (Phase 6)",
        "",
        "Generated by `pagerank.py`.",
        "",
        f"- Nodes (corpus documents): {N:,}",
        f"- Edges (citations inside the corpus): {edges:,}",
        f"- Documents citing nothing in the corpus (dangling): "
        f"{sum(1 for v in pr if not cites.get(v)):,}",
        f"- Documents nobody in the corpus cites: {sum(1 for v in pr if cited_by[v] == 0):,}",
        f"- Converged in {iterations} iterations (damping {DAMPING}, tolerance {TOLERANCE})",
        "",
        "PR × N: 1.0 = an average document.",
        "",
        "## Top 15 documents",
        "", *table(ranked[:15]),
        "",
        "## Top 15 judgments (statutes left out)",
        "", *table([d for d in ranked if info[d]["type"] == "judgment"][:15]),
    ]
    REPORT_FILE.parent.mkdir(exist_ok=True)
    REPORT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")

def load_judgment_pagerank() -> dict[str, float]:
    """{doc_id: PageRank} for judgments only, from data/pagerank.tsv (used by ranking.py)."""
    with PAGERANK_FILE.open(encoding="utf-8") as f:
        rows = (line.split("	") for line in f)
        return {doc_id: float(value) for doc_id, doc_type, value in rows if doc_type == "judgment"}


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    nodes, cites, info = load_graph()
    pr, iterations = pagerank(nodes, cites)
    with PAGERANK_FILE.open("w", encoding="utf-8") as f:
        for doc_id in nodes:
            f.write(f"{doc_id}\t{info[doc_id]['type']}\t{pr[doc_id]:.12e}\n")
    write_report(pr, cites, info, iterations)
    print(REPORT_FILE.read_text(encoding="utf-8"))
